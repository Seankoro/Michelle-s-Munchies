/** Centre of the sector a 6-digit postal code belongs to, or null. */
export function sectorCentre(postal: string): LatLng | null {
  if (!/^\d{6}$/.test(postal)) return null;
  return SECTOR_CENTRES[postal.slice(0, 2)] ?? null;
}
